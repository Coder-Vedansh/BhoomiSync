import hashlib
import json
from datetime import datetime
from typing import Dict, Any, Optional
from sqlalchemy.orm import Session

from app.models.survey import Survey
from app.models.parcel import Parcel, VerificationStatus
from app.models.land_records import LandParcel, LandRecord, CadastralVersion, ParcelChangeRecord
from app.models.ingestion import Sensor, UploadedFile, PositionRecord
from app.models.ai_results import AIClassificationResult, AIBoundaryResult, AIChangeResult
